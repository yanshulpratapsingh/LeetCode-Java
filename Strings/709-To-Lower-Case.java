/*
 * LeetCode: 709. To Lower Case
 * Difficulty: Easy
 * Topic: String
 *
 * Approach:
 * Convert the given string into lowercase.
 *
 * Java provides the built-in toLowerCase() method
 * which converts all uppercase characters into lowercase.
 *
 * Time Complexity: O(n)
 * Space Complexity: O(n)
 */

class Solution {

    public String toLowerCase(String s) {

        return s.toLowerCase();
    }
}